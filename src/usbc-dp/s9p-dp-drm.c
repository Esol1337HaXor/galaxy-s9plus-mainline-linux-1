static irqreturn_t decon2_irq(int irq, void *data)
{
	struct s9p_dp *dp = data;

	/* DECON2's APB may be gated while its interrupts are off: never read it then */
	if (!dp->d2_irq_armed)
		return IRQ_NONE;
	/* always read and clear: the line is level-triggered */
	if (!s9p_dp_decon_irq(dp) || !dp->streaming)
		return IRQ_HANDLED;
	drm_crtc_handle_vblank(&dp->pipe.crtc);
	spin_lock(&dp->drm.event_lock);
	/* complete the flip only once its address has been latched */
	if (dp->event && s9p_dp_decon_latched(dp)) {
		drm_crtc_send_vblank_event(&dp->pipe.crtc, dp->event);
		drm_crtc_vblank_put(&dp->pipe.crtc);
		dp->event = NULL;
	}
	spin_unlock(&dp->drm.event_lock);
	return IRQ_HANDLED;
}

