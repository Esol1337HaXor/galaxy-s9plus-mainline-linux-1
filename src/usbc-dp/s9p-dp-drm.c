static struct gpio_desc *usb_con_sel;	/* gpg0-4, CC orientation from the MCU */

void dp_log(struct s9p_dp *dp, const char *fmt, ...)
{
	va_list ap;
	char line[256];
	unsigned long flags;
	int n;

	va_start(ap, fmt);
	n = vscnprintf(line, sizeof(line), fmt, ap);
	va_end(ap);
	dev_info(dp->dev, "%s\n", line);
	spin_lock_irqsave(&dp->log_lock, flags);
	if (dp->log_len + n + 2 >= sizeof(dp->log)) {
		size_t keep = dp->log_len / 2;

		memmove(dp->log, dp->log + dp->log_len - keep, keep);
		dp->log_len = keep;
	}
	memcpy(dp->log + dp->log_len, line, n);
	dp->log_len += n;
	dp->log[dp->log_len++] = '\n';
	spin_unlock_irqrestore(&dp->log_lock, flags);
}

