/* orientation                                                          */

static void get_usb_con_sel(void)
{
	struct gpio_device *gdev = gpio_device_find_by_label("gpg0");
	struct gpio_desc *d;

	if (!gdev)
		gdev = gpio_device_find_by_label("gpg0-gpio-bank");
	if (!gdev)
		return;
	d = s9p_grab_gpio(gdev, 4, "dp-usb-con-sel", GPIOD_IN);
	if (!IS_ERR(d))
		usb_con_sel = d;
	gpio_device_put(gdev);
}

/* vendor: dp_sw_sel = gpio(gpg0-4) (1 = CC2); the MCU's CC_STATUS0 as fallback */
static u8 orientation(struct s9p_dp *dp)
{
	int g = usb_con_sel ? gpiod_get_raw_value_cansleep(usb_con_sel) : -1;
	u8 cc = dp->st.orientation;

	dp_log(dp, "orientation: gpg0-4 = %d, MCU CC%u", g, cc);
	if (!strcmp(orient, "cc") || g < 0)
		return cc ? cc : 1;
	if (!strcmp(orient, "gpio") || !cc)
		return g ? 2 : 1;
	if ((g ? 2 : 1) != cc)
		dp_log(dp, "gpg0-4 and the MCU disagree: using gpg0-4 (as the vendor)");
	return g ? 2 : 1;
}

