/* only contiguous buffers the 32-bit IDMA can reach */
static struct drm_gem_object *
s9p_dp_import_sg_table(struct drm_device *drm, struct dma_buf_attachment *attach,
		       struct sg_table *sgt)
{
	size_t size = attach->dmabuf->size;

	if (drm_prime_get_contiguous_size(sgt) < size ||
	    sg_dma_address(sgt->sgl) + size > SZ_4G)
		return ERR_PTR(-EINVAL);
	return drm_gem_dma_prime_import_sg_table(drm, attach, sgt);
}

