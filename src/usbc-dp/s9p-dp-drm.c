static void send_event(struct s9p_dp *dp, struct drm_crtc *crtc,
		       struct drm_crtc_state *cs)
{
	unsigned long flags;

	if (!cs->event)
		return;
	spin_lock_irqsave(&dp->drm.event_lock, flags);
	if (dp->streaming && dp->irq_ok && !dp->event &&
	    drm_crtc_vblank_get(crtc) == 0) {
		dp->event = cs->event;
	} else {
		drm_crtc_send_vblank_event(crtc, cs->event);
	}
	cs->event = NULL;
	spin_unlock_irqrestore(&dp->drm.event_lock, flags);
}

static void pipe_enable(struct drm_simple_display_pipe *pipe,
			struct drm_crtc_state *cs, struct drm_plane_state *ps)
{
	struct s9p_dp *dp = to_s9p_dp(pipe->crtc.dev);
	struct drm_display_mode *m = &cs->adjusted_mode;
	struct drm_framebuffer *fb = ps->fb;
	int ret = -ENODEV;

	mutex_lock(&dp->lock);
	/*
	 * Back from blanking: the same sequence as the first start, controller
	 * and PHY reset included. Restarting DECON2, the video stream or even
	 * the training under a running controller left the picture shifted
	 * (and wrapped) by a random amount; only a fresh controller starts it
	 * aligned with DECON2.
	 */
	if (dp->connected) {
		bool was_blanked = dp->blanked;

		stop_output(dp);
		ret = 0;
		if (was_blanked) {
			dp->phy_ready = false;
			dp->trained = false;
			ret = s9p_dp_hw_up(dp);
		}
		if (!ret)
			ret = s9p_dp_train(dp, m);
		if (!ret)
			ret = s9p_dp_video_on(dp, m, false);
		if (!ret)
			ret = s9p_dp_decon_on(dp, m, drm_fb_dma_get_gem_addr(fb, ps, 0),
					      fb->pitches[0]);
		if (ret)
			s9p_dp_video_off(dp);
	}
	mutex_unlock(&dp->lock);
	if (ret)
		dp_log(dp, "modeset %dx%d failed: %d", m->hdisplay, m->vdisplay, ret);
	drm_crtc_vblank_on(&pipe->crtc);
	send_event(dp, &pipe->crtc, cs);
}

static void pipe_disable(struct drm_simple_display_pipe *pipe)
{
	struct s9p_dp *dp = to_s9p_dp(pipe->crtc.dev);

	drm_crtc_vblank_off(&pipe->crtc);
	mutex_lock(&dp->lock);
	/*
	 * Screen blanking: keep the link and the video stream up with a black
	 * frame. Without a signal some USB-C/HDMI adapters go into a standby
	 * where AUX no longer answers, and only a replug wakes them.
	 */
	if (dp->connected && dp->trained && dp->streaming && keep_link) {
		struct drm_display_mode m;

		drm_mode_copy(&m, &dp->cur_mode);
		s9p_dp_decon_off(dp);
		if (!start_pattern(dp, &m, 0x000000)) {
			dp->blanked = true;
			dp_log(dp, "blank: link kept up, black frame");
			mutex_unlock(&dp->lock);
			return;
		}
	}
	stop_output(dp);
	mutex_unlock(&dp->lock);
}

static void pipe_update(struct drm_simple_display_pipe *pipe,
			struct drm_plane_state *old)
{
	struct s9p_dp *dp = to_s9p_dp(pipe->crtc.dev);
	struct drm_plane_state *ps = pipe->plane.state;
	struct drm_crtc_state *cs = pipe->crtc.state;

	if (ps->fb) {
		dma_addr_t addr = drm_fb_dma_get_gem_addr(ps->fb, ps, 0);

		mutex_lock(&dp->lock);
		if (dp->streaming && (addr != dp->scanout || ps->fb->pitches[0] != dp->pitch))
			s9p_dp_decon_flip(dp, addr, ps->fb->pitches[0]);
		mutex_unlock(&dp->lock);
	}
	send_event(dp, &pipe->crtc, cs);
}

static enum drm_mode_status pipe_mode_valid(struct drm_simple_display_pipe *pipe,
					    const struct drm_display_mode *mode)
{
	return mode->clock > max_clock ? MODE_CLOCK_HIGH : MODE_OK;
}

static int pipe_enable_vblank(struct drm_simple_display_pipe *pipe)
{
	struct s9p_dp *dp = to_s9p_dp(pipe->crtc.dev);

	/* no vblank without a running DECON2: commits then skip the wait */
	if (!dp->irq_ok || !dp->streaming)
		return -EINVAL;
	dp->vblank_on = true;
	if (dp->streaming)
		s9p_dp_decon_vblank(dp, true);
	return 0;
}

static void pipe_disable_vblank(struct drm_simple_display_pipe *pipe)
{
	struct s9p_dp *dp = to_s9p_dp(pipe->crtc.dev);

	dp->vblank_on = false;
	/* FRAME_START stays enabled while streaming: it completes flips */
}

