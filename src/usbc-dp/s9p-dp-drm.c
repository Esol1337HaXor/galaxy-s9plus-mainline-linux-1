/* DECON2 frame start: GIC SPI 194, level high */
static int map_decon2_irq(void)
{
	struct device_node *gic = of_find_node_by_path("/soc@0/interrupt-controller@10101000");
	struct irq_fwspec spec = {
		.param_count = 3,
		.param = { 0 /* SPI */, 194, IRQ_TYPE_LEVEL_HIGH },
	};
	int irq;

	if (!gic)
		return -ENODEV;
	spec.fwnode = of_fwnode_handle(gic);
	irq = irq_create_fwspec_mapping(&spec);
	of_node_put(gic);
	return irq ? irq : -EINVAL;
}

