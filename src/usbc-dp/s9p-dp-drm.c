static int conn_get_modes(struct drm_connector *conn)
{
	struct s9p_dp *dp = to_s9p_dp(conn->dev);
	const struct drm_edid *e;
	int n;

	mutex_lock(&dp->lock);
	e = dp->edid ? drm_edid_dup(dp->edid) : NULL;
	mutex_unlock(&dp->lock);
	drm_edid_connector_update(conn, e);
	n = drm_edid_connector_add_modes(conn);
	drm_edid_free(e);
	if (!n && dp->connected) {
		/* no EDID (some HDMI adapters): the safe CEA modes */
		n = drm_add_modes_noedid(conn, 1920, 1080);
		drm_set_preferred_mode(conn, 1280, 720);
	}
	return n;
}

static enum drm_mode_status conn_mode_valid(struct drm_connector *conn,
					    const struct drm_display_mode *mode)
{
	struct s9p_dp *dp = to_s9p_dp(conn->dev);

	if (mode->clock > max_clock)
		return MODE_CLOCK_HIGH;
	if (mode->hdisplay > 4096 || mode->vdisplay > 4096)
		return MODE_BAD;
	if (mode->flags & DRM_MODE_FLAG_INTERLACE)
		return MODE_NO_INTERLACE;
	if (!s9p_dp_mode_fits(dp, mode->clock))
		return MODE_CLOCK_HIGH;
	return MODE_OK;
}

static int conn_detect_ctx(struct drm_connector *conn,
			   struct drm_modeset_acquire_ctx *ctx, bool force)
{
	struct s9p_dp *dp = to_s9p_dp(conn->dev);

	return dp->connected ? connector_status_connected : connector_status_disconnected;
}

