/*
 * USB-C DisplayPort output for the Galaxy S9+ (star2lte, Exynos 9810).
 *
 * A display-only DRM device ("s9p-dp", one CRTC/plane/DP connector) next
 * to the panel's "exynos" device: GNOME/mutter treats it like any other
 * secondary display (as it does a DisplayLink adapter). The pieces:
 *
 *   s9p-usbc     MAX77705 DP alt mode -> pin assignment, orientation, HPD
 *   s9p-dp-board PCAL6524 expander -> SBU/AUX analog switch
 *   s9p-dp-hw    combo PHY, DP controller, AUX, link training, video,
 *                DECON2 + DPU DMA scanout
 *   this file    DRM glue, hotplug, vblank, debugfs bring-up commands
 *
 * debugfs (/sys/kernel/debug/s9p-dp/): "log", "regs", "state" and "cmd",
 * which takes bring-up steps one at a time:
 *   aux on|off      close/open the SBU switch (orientation from s9p-usbc)
 *   up              PMA + DP PHY + controller (AUX usable afterwards)
 *   probe           read DPCD caps and the EDID
 *   train [vic]     link training for CEA mode vic (default 16, 1080p60)
 *   bist [vic]      train + colour bars generated by the DP controller
 *   pattern [vic]   train + DECON2 scanning a test pattern from memory
 *   off             stop everything
 *   fake <pin> <cc> pretend alt mode said pin (C/D/E) and orientation 1/2
 */
